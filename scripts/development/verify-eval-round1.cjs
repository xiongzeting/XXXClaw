// Local, headless UI smoke check. Does not use a logged-in or visible browser.
const { chromium } = require('C:/Users/inari/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, '.aster/frontend-eval-round1');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1040 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root, 'frontend/eval-round1/dashboard.html')).href);
    await page.locator('#case-rows tr').last().waitFor();
    assert.equal(await page.locator('#case-rows tr').count(), 30);
    await page.screenshot({ path: path.join(output, 'desktop.png') });
    await page.locator('#composition').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'composition.png') });
    await page.selectOption('#category-filter', 'compression');
    assert.equal(await page.locator('#case-rows tr').count(), 6);
    const pendingDownload = page.waitForEvent('download');
    await page.click('#export-csv');
    const download = await pendingDownload;
    await download.saveAs(path.join(output, 'filtered.csv'));
    assert.equal(fs.readFileSync(path.join(output, 'filtered.csv'),'utf8').trim().split(/\r?\n/).length,7);
    await page.selectOption('#status-filter', 'oracle');
    assert.equal(await page.locator('#case-rows tr').count(), 0);
    assert.equal(await page.locator('#empty-state').isVisible(), true);
    await page.click('#reset');
    await page.selectOption('#status-filter', 'oracle');
    assert.equal(await page.locator('#case-rows tr').count(), 4);
    await page.click('#reset');
    await page.selectOption('#dimension-filter', 'outcome');
    assert.equal(await page.locator('#case-rows tr').count(), 1);
    assert.match(await page.locator('#case-rows').innerText(), /cash_refund_reconciliation/);
    await page.click('#reset');
    await page.selectOption('#status-filter', 'passed');
    assert.equal(await page.locator('#case-rows tr').count(), 15);
    await page.click('#reset');
    await page.selectOption('#status-filter', 'network');
    assert.equal(await page.locator('#case-rows tr').count(), 6);
    assert.equal(await page.locator('#case-rows td:nth-child(7) .fail').count(), 0);
    await page.locator('#case-rows .case-link').first().click();
    assert.match(await page.locator('#case-detail').innerText(), /直接计为通过/);
    await page.keyboard.press('Escape');
    await page.click('#reset');
    await page.selectOption('#dimension-filter', 'reliability');
    assert.equal(await page.locator('#case-rows tr').count(), 3);
    assert.equal(await page.locator('#split-results thead th').count(),3);
    assert.equal(await page.locator('#split-filter option[value="retained"]').count(),0);
    assert.match(await page.locator('#next-efficiency-policy').innerText(), /不设硬门槛/);
    for (const split of ['development','test']) {
      await page.click('#reset');
      await page.selectOption('#split-filter',split);
      assert.equal(await page.locator('#case-rows tr').count(),15);
    }
    await page.click('#reset');
    await page.fill('#search', 'version_resolution');
    assert.equal(await page.locator('#case-rows tr').count(), 1);
    await page.locator('#case-rows .case-link').click();
    assert.equal(await page.locator('#case-dialog').isVisible(), true);
    assert.match(await page.locator('#case-detail').innerText(), /553,471/);
    await page.screenshot({ path: path.join(output, 'case-detail.png') });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#case-dialog').isVisible(), false);
    await page.click('#reset');
    await page.click('#sort-tokens');
    assert.match(await page.locator('#case-rows tr').first().innerText(), /version_resolution/);
    await page.screenshot({ path: path.join(output, 'case-table.png') });
    await page.click('#sort-errors');
    const mostErrors = await page.evaluate(() => [...window.EVAL_ROUND1.cases].sort((a,b)=>b.metrics.tool_errors-a.metrics.tool_errors)[0].family);
    assert.match(await page.locator('#case-rows tr').first().innerText(), new RegExp(mostErrors));
    await page.click('#sort-time');
    const longest = await page.evaluate(() => [...window.EVAL_ROUND1.cases].sort((a,b)=>b.seconds-a.seconds)[0].family);
    assert.match(await page.locator('#case-rows tr').first().innerText(), new RegExp(longest));
    await page.locator('#improvements').scrollIntoViewIfNeeded();
    assert.equal(await page.locator('#improvements .improvement').count(), 4);
    assert.match(await page.locator('#improvements').innerText(), /94,457/);
    assert.match(await page.locator('#improvements').innerText(), /3.122/);
    assert.match(await page.locator('#efficiency-retest-update').innerText(), /1,730,372/);
    assert.match(await page.locator('#efficiency-retest-update').innerText(), /已定位、尚待修复/);
    assert.match(await page.locator('#goal-completion-update').innerText(), /5 次→0 次/);
    await page.locator('#latest-improvements').screenshot({path:path.join(output,'latest-improvements.png')});
    await page.screenshot({ path: path.join(output, 'improvements.png') });
    await page.locator('#eval-evolution').scrollIntoViewIfNeeded();
    assert.equal(await page.locator('#eval-evolution .evolution-card').count(), 6);
    await page.screenshot({ path: path.join(output, 'eval-evolution.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'}));
    await page.screenshot({ path: path.join(output, 'mobile.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.locator('#latest-improvements').screenshot({path:path.join(output,'latest-improvements-mobile.png')});
    await page.locator('#case-rows .case-link').first().click();
    assert.equal(await page.locator('#case-dialog').isVisible(), true);
    await page.click('#close-dialog');
    assert.equal(await page.locator('#case-dialog').isVisible(), false);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output,'checks.json'), JSON.stringify({passed:true,cases:30,displayPassed:15,networkCountedPassed:6,reliabilityPassed:27,compression:6,correctedOracleOnly:4,outcomeFailures:1,improvements:4,desktop:[1440,1040],mobile:[390,844],consoleErrors:errors,checks:['data counts','combined filters','empty state','search','detail evidence','keyboard close','three metric sorts','CSV export','network scoring convention','improvement evidence','efficiency retest and Goal records','mobile overflow','mobile dialog']},null,2));
    console.log('UI checks passed: filters, details, evidence, CSV, keyboard, mobile; no page errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
